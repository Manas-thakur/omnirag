"""Generate the CLI reference page of the docs site from the real ``omnirag`` command.

Usage::

    uv run python scripts/gen_cli_docs.py            # writes the page
    uv run python scripts/gen_cli_docs.py --check    # exits 1 if the page is out of date

The page is built by walking the Click-style command tree that Typer creates, so every
command, argument and option (with its short flag, default, environment
variable and help text) comes from ``src/omnirag/cli.py`` itself.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import typer

from omnirag.cli import app

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "site" / "src" / "content" / "docs" / "docs" / "reference" / "cli.md"

HEADER = """---
title: CLI reference
description: Every omnirag command, argument and option.
---

<!-- Generated by scripts/gen_cli_docs.py from src/omnirag/cli.py. Do not edit by hand. -->

The `omnirag` command is installed with the package. Run `omnirag COMMAND --help` for the same
information in the terminal.

**Global option:** `--data-dir` / `-d PATH` (or the `OMNIRAG_HOME` environment variable)
selects where knowledge bases live; the default is `~/.omnirag`. It goes before the command:
`omnirag -d ./data kb list`. Commands that take `--kb` / `-b` default to the knowledge base
named by `OMNIRAG_KB`, or `default`.

| Command | Description |
| ------- | ----------- |
"""


def clean(text: str | None) -> str:
    """Collapse whitespace and drop Rich markup escapes from help text."""
    text = (text or "").replace("\\[", "[")
    return re.sub(r"\s+", " ", text).strip()


# Typer vendors its own copy of Click, so parameters are recognised by shape, not by class.
def is_option(param) -> bool:
    return getattr(param, "param_type_name", "") == "option"


def is_argument(param) -> bool:
    return getattr(param, "param_type_name", "") == "argument"


def is_group(cmd) -> bool:
    return hasattr(cmd, "list_commands")


def cell(text: str) -> str:
    """Make text safe in a Markdown table cell: pipes, and <placeholders> that read as HTML."""
    return text.replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")


def default_of(param) -> str:
    if param.default in (None, "", ()) or callable(param.default):
        return ""
    if is_option(param) and param.is_flag and not param.secondary_opts:
        return ""
    if isinstance(param.default, bool) and is_option(param) and param.secondary_opts:
        return param.opts[0] if param.default else param.secondary_opts[0]
    return f"`{param.default}`"


def type_of(param) -> str:
    if is_option(param) and param.is_flag:
        return "flag"
    annotation = param.type_descriptor.annotation
    many = getattr(annotation, "__origin__", None) is list
    inner = annotation.__args__[0] if many else annotation
    name = {int: "integer", str: "text", float: "number", Path: "path"}.get(inner, str(inner))
    if inner is int and param.min is not None and param.max is not None:
        name = f"integer {param.min}–{param.max}"
    if many:
        name += ", repeatable" if is_option(param) else ", one or more"
    return name


def usage(path: list[str], cmd) -> str:
    parts = ["omnirag", *path]
    for p in cmd.params:
        if is_argument(p):
            metavar = p.name.upper()
            parts.append(f"{metavar}..." if p.nargs == -1 else metavar)
    if any(is_option(p) and p.name != "help" for p in cmd.params):
        parts.append("[OPTIONS]")
    return " ".join(parts)


def section(path: list[str], cmd) -> str:
    title = " ".join(["omnirag", *path])
    lines = [f"## `{title}`", "", clean(cmd.help), "", "```bash", usage(path, cmd), "```", ""]
    args = [p for p in cmd.params if is_argument(p)]
    opts = [p for p in cmd.params if is_option(p) and p.name != "help"]
    if args:
        lines += ["| Argument | Type | Description |", "| -------- | ---- | ----------- |"]
        for a in args:
            help_text = clean(getattr(a, "help", "")) or "Required."
            lines.append(f"| `{a.name.upper()}` | {type_of(a)} | {cell(help_text)} |")
        lines.append("")
    if opts:
        lines += [
            "| Option | Type | Default | Description |",
            "| ------ | ---- | ------- | ----------- |",
        ]
        for o in opts:
            flags = " / ".join(f"`{f}`" for f in [*o.opts, *o.secondary_opts])
            desc = clean(o.help)
            if o.envvar:
                envs = o.envvar if isinstance(o.envvar, (list, tuple)) else [o.envvar]
                desc = f"{desc} Env: {', '.join(f'`{e}`' for e in envs)}.".strip()
            lines.append(f"| {flags} | {type_of(o)} | {default_of(o)} | {cell(desc)} |")
        lines.append("")
    return "\n".join(lines)


def walk(group, path: list[str]):
    ctx = typer.Context(group)
    for name in group.list_commands(ctx):
        cmd = group.get_command(ctx, name)
        if cmd is None or cmd.hidden:
            continue
        if is_group(cmd):
            yield from walk(cmd, [*path, name])
        else:
            yield [*path, name], cmd


def render() -> str:
    root = typer.main.get_command(app)
    assert is_group(root)
    commands = list(walk(root, []))
    # Knowledge-base management first, then the everyday commands in a natural order.
    order = ["kb", "ingest", "query", "search", "stats", "remove", "serve", "doctor"]
    commands.sort(key=lambda item: order.index(item[0][0]) if item[0][0] in order else 99)
    table = [
        f"| [`omnirag {' '.join(p)}`](#{anchor(p)}) | {cell(clean(c.help).rstrip('.'))} |"
        for p, c in commands
    ]
    body = "\n".join(section(p, c) for p, c in commands)
    return HEADER + "\n".join(table) + "\n\n" + body.rstrip() + "\n"


def anchor(path: list[str]) -> str:
    return "omnirag-" + "-".join(path)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run scripts/gen_cli_docs.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
